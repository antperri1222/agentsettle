// Regenerates sdk/artifacts.ts from Foundry build output. Run: npm run build:contracts
import { readFileSync, writeFileSync } from 'node:fs';

const load = (name) => JSON.parse(readFileSync(new URL(`../contracts/out/${name}.sol/${name}.json`, import.meta.url)));
const escrow = load('AgentEscrow');
const mock = load('MockUSDC');
const out = `// AUTO-GENERATED by scripts/gen-artifacts.mjs from contracts/out. Do not edit by hand.
export const agentEscrowAbi = ${JSON.stringify(escrow.abi, null, 2)} as const;

export const agentEscrowBytecode = ${JSON.stringify(escrow.bytecode.object)} as const;

export const mockUsdcAbi = ${JSON.stringify(mock.abi, null, 2)} as const;

/** TEST-ONLY token bytecode. Used solely for local Anvil deployments. */
export const mockUsdcBytecode = ${JSON.stringify(mock.bytecode.object)} as const;
`;
writeFileSync(new URL('../sdk/artifacts.ts', import.meta.url), out);
console.log('wrote sdk/artifacts.ts');
